"""Original tests/Database/Security/RowLevelSecurityTest.php (ADR 0003 proof of concept).

Two tables shaped like ``student_records`` and ``enrollments`` with the policy pattern used from
Phase 2 on: owner, global permission holder, system context. They are created (committed) by the
schema owner for this module and dropped afterwards. The real policies on ``people``,
``student_records`` etc. are tested with their models (Phase 2, StudentRecordAccessTest)."""

