POC_DDL = """
DROP TABLE IF EXISTS rls_poc_enrollments, rls_poc_student_records;

CREATE TABLE rls_poc_student_records (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    student_number text NOT NULL
);
CREATE TABLE rls_poc_enrollments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_record_id bigint NOT NULL REFERENCES rls_poc_student_records (id),
    grade text
);
CREATE INDEX ON rls_poc_student_records (user_id);
CREATE INDEX ON rls_poc_enrollments (student_record_id);

ALTER TABLE rls_poc_student_records ENABLE ROW LEVEL SECURITY;
ALTER TABLE rls_poc_enrollments ENABLE ROW LEVEL SECURITY;

CREATE POLICY rls_poc_student_records_owner_select ON rls_poc_student_records
    FOR SELECT USING (user_id = (SELECT util.current_user_id()));
CREATE POLICY rls_poc_student_records_staff_all ON rls_poc_student_records
    FOR ALL USING ((SELECT util.has_permission('rls_poc.view')))
    WITH CHECK ((SELECT util.has_permission('rls_poc.view')));
CREATE POLICY rls_poc_student_records_system_all ON rls_poc_student_records
    FOR ALL USING ((SELECT util.is_system_context())) WITH CHECK ((SELECT util.is_system_context()));

CREATE POLICY rls_poc_enrollments_owner_select ON rls_poc_enrollments
    FOR SELECT USING (student_record_id IN (
        SELECT sr.id FROM rls_poc_student_records AS sr WHERE sr.user_id = (SELECT util.current_user_id())
    ));
CREATE POLICY rls_poc_enrollments_staff_all ON rls_poc_enrollments
    FOR ALL USING ((SELECT util.has_permission('rls_poc.view')))
    WITH CHECK ((SELECT util.has_permission('rls_poc.view')));
CREATE POLICY rls_poc_enrollments_system_all ON rls_poc_enrollments
    FOR ALL USING ((SELECT util.is_system_context())) WITH CHECK ((SELECT util.is_system_context()));
"""


@pytest.fixture(scope="module", autouse=True)
def poc_tables(django_db_setup: None, django_db_blocker: Any) -> Iterator[None]:
    with django_db_blocker.unblock():
        owner = connections["migrator"]
        with owner.cursor() as cursor:
            cursor.execute(POC_DDL)
        owner.close()
    yield
    with django_db_blocker.unblock():
        with owner.cursor() as cursor:
            cursor.execute("DROP TABLE IF EXISTS rls_poc_enrollments, rls_poc_student_records")
        owner.close()


