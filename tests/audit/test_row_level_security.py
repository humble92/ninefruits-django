def _records() -> list[Any]:
    with connection.cursor() as cursor:
        cursor.execute("SELECT user_id FROM rls_poc_student_records ORDER BY id")
        return [row[0] for row in cursor.fetchall()]


def _count(table: str) -> int:
    sql = {
        "records": "SELECT count(*) FROM rls_poc_student_records",
        "enrollments": "SELECT count(*) FROM rls_poc_enrollments",
    }[table]
    return int(scalar(sql))


def test_shows_users_only_their_own_rows_including_in_related_tables(students: dict[str, Any]) -> None:
    session_context().for_user(students["alice"].pk)

    assert _records() == [students["alice"].pk]
    assert _count("enrollments") == 2

    session_context().for_user(students["bob"].pk)

    assert _records() == [students["bob"].pk]


def test_returns_nothing_without_a_request_context(students: dict[str, Any]) -> None:
    assert _count("records") == 0
    assert _count("enrollments") == 0


def test_blocks_a_direct_lookup_of_another_user_record_even_when_the_id_is_known(students: dict[str, Any]) -> None:
    session_context().for_system("test:lookup")
    bob_record_id = scalar("SELECT id FROM rls_poc_student_records WHERE user_id = %s", [students["bob"].pk])
    assert bob_record_id is not None

    session_context().for_user(students["alice"].pk)

    assert scalar("SELECT id FROM rls_poc_student_records WHERE id = %s", [bob_record_id]) is None
    with connection.cursor() as cursor:
        cursor.execute("UPDATE rls_poc_student_records SET student_number = 'x' WHERE id = %s", [bob_record_id])
        assert cursor.rowcount == 0


def _grant_global(user: Any, permission: str) -> int:
    """Role with one permission, assigned globally (raw SQL: the security models are tested
    separately). Returns the assignment id."""
    session_context().for_system("test:grant")
    with connection.cursor() as cursor:
        cursor.execute(
            "INSERT INTO permissions (name, guard_name) VALUES (%s, 'web') "
            "ON CONFLICT (name, guard_name) DO UPDATE SET name = EXCLUDED.name RETURNING id",
            [permission],
        )
        permission_id = cursor.fetchone()[0]
        cursor.execute(
            "INSERT INTO roles (name, guard_name, display_name) "
            "VALUES (%s, 'web', '{\"en\": \"RLS PoC\"}') RETURNING id",
            [f"rls-poc-{user.pk}"],
        )
        role_id = cursor.fetchone()[0]
        cursor.execute(
            "INSERT INTO role_has_permissions (permission_id, role_id) VALUES (%s, %s)", [permission_id, role_id]
        )
        cursor.execute(
            "INSERT INTO role_assignments (user_id, role_id, scope_type, reason) "
            "VALUES (%s, %s, 'global', 'test') RETURNING id",
            [user.pk, role_id],
        )
        assignment_id = cursor.fetchone()[0]
    session_context().use_baseline({})
    return int(assignment_id)


def test_lets_users_with_a_global_permission_see_every_row_while_the_assignment_is_active(
    students: dict[str, Any],
) -> None:
    staff = make_user()
    assignment_id = _grant_global(staff, "rls_poc.view")
    session_context().for_user(staff.pk)

    assert _count("records") == 2

    session_context().for_system("test:revoke")
    with connection.cursor() as cursor:
        cursor.execute(
            "UPDATE role_assignments SET ends_at = now() - interval '1 minute', starts_at = NULL WHERE id = %s",
            [assignment_id],
        )
    session_context().for_user(staff.pk)

    assert _count("records") == 0


def test_does_not_let_users_write_rows_they_cannot_see(students: dict[str, Any]) -> None:
    session_context().for_user(students["alice"].pk)

    def forge() -> None:
        with connection.cursor() as cursor:
            cursor.execute(
                "INSERT INTO rls_poc_student_records (user_id, student_number) VALUES (%s, 'forged')",
                [students["alice"].pk],
            )

    assert "row-level security" in (database_error(forge) or "")


@shared_task(name="tests.count_rls_poc_records", base=SystemTask)
def count_rls_poc_records() -> int:
    return _count("records")


def test_gives_celery_tasks_the_system_context_and_clears_it_afterwards(students: dict[str, Any]) -> None:
    assert count_rls_poc_records.delay().get() == 2
    assert session_context().current()["app.actor"] == ""


def _rls_count_view(request: HttpRequest) -> JsonResponse:
    return JsonResponse({"count": _count("records")})


urlpatterns = [path("_test/rls-count", _rls_count_view)]


@pytest.mark.urls(__name__)
def test_clears_the_user_context_when_a_request_ends(students: dict[str, Any], client: Client) -> None:
    client.force_login(students["alice"])

    assert client.get("/_test/rls-count").json() == {"count": 1}

    # Same connection, after the request: nothing is left behind.
    assert _count("records") == 0
    assert session_context().current()["app.user_id"] == ""
