"""Factories for people, student records and instructors (original ``Database\\Factories\\Person``).

People get names from mixed Faker locales (en_US, ko_KR, zh_CN). Emails use the reserved
``.test`` domain; no real-looking national IDs are generated by default."""

from __future__ import annotations

import random
from datetime import date, timedelta
from typing import Any

import factory
from django.utils import timezone
from faker import Faker

from ninefruits.person.enums import (
    AdvisorRole,
    EmploymentType,
    Gender,
    GuardianRelationship,
    StatusChangeStatus,
    StudentStatus,
)
from ninefruits.person.models import (
    AdvisorAssignment,
    Guardian,
    Instructor,
    Person,
    StudentRecord,
    StudentStatusChange,
    StudentStatusChangeType,
)

from .organization import OrgUnitFactory, ProgramFactory

_fakers = {locale: Faker(locale) for locale in ("en_US", "ko_KR", "zh_CN")}


def _variants(locale: str) -> dict[str, str] | None:
    local = _fakers[locale]
    if locale == "ko_KR":
        return {"ko": local.last_name() + local.first_name()}
    if locale == "zh_CN":
        return {"zh-hans": local.last_name() + local.first_name()}
    return None


class PersonFactory(factory.django.DjangoModelFactory):
    """``PersonFactory(national_id="TEST-...")``, ``PersonFactory(with_account=True)``."""

    class Meta:
        model = Person
        skip_postgeneration_save = True

    class Params:
        locale = factory.LazyFunction(lambda: random.choice(["en_US", "ko_KR", "zh_CN"]))
        national_id = None

    gender = factory.LazyFunction(lambda: random.choice([Gender.FEMALE, Gender.MALE]))
    family_name = factory.Faker("last_name", locale="en_US")
    given_name = factory.LazyAttribute(
        lambda person: (
            _fakers["en_US"].first_name_female()
            if person.gender == Gender.FEMALE
            else _fakers["en_US"].first_name_male()
        )
    )
    name_variants = factory.LazyAttribute(lambda person: _variants(person.locale))
    birth_date = factory.Faker("date_between", start_date="-30y", end_date="-18y")
    email = factory.Sequence(lambda n: f"person{n}@example.test")
    phone = factory.Faker("numerify", text="010-####-####")

    @factory.lazy_attribute
    def national_id_encrypted(self) -> str | None:
        """A fictional national ID (letters cannot occur in real numbers) when ``national_id=True``."""
        if self.national_id is True:
            return "TEST-" + _fakers["en_US"].unique.numerify("##########")
        return self.national_id or None

    @factory.post_generation
    def with_account(self, create: bool, extracted: Any, **kwargs: Any) -> None:
        if create and extracted:
            from .security import UserFactory

            UserFactory(person=self, email=self.email or f"person{self.pk}@example.test", name=None, **kwargs)


class GuardianFactory(factory.django.DjangoModelFactory):
    class Meta:
        model = Guardian

    person = factory.SubFactory(PersonFactory)
    relationship = factory.LazyFunction(
        lambda: random.choice([GuardianRelationship.FATHER, GuardianRelationship.MOTHER])
    )
    full_name = factory.Faker("name")
    phone = factory.Faker("numerify", text="010-####-####")


class StudentRecordFactory(factory.django.DjangoModelFactory):
    """``StudentRecordFactory(program=program)``, ``StudentRecordFactory(graduated=True)``,
    ``StudentRecordFactory(status=StudentStatus.ON_LEAVE)``."""

    class Meta:
        model = StudentRecord

    class Params:
        year = factory.LazyFunction(lambda: random.randint(2022, 2026))
        graduated = factory.Trait(
            status=StudentStatus.GRADUATED,
            graduation_date=factory.LazyAttribute(
                lambda record: record.admission_date.replace(year=record.admission_date.year + 4) - timedelta(days=1)
            ),
        )

    person = factory.SubFactory(PersonFactory)
    student_number = factory.Sequence(lambda n: f"T{n:08d}")
    program = factory.SubFactory(ProgramFactory)
    org_unit = factory.LazyAttribute(lambda record: record.program.org_unit)
    admission_date = factory.LazyAttribute(lambda record: date(record.year, 3, 1))
    catalog_year = factory.LazyAttribute(lambda record: record.year)
    year_level = 1
    status = StudentStatus.ENROLLED


class InstructorFactory(factory.django.DjangoModelFactory):
    class Meta:
        model = Instructor

    person = factory.SubFactory(PersonFactory)
    employee_number = factory.Sequence(lambda n: f"F{n:05d}")
    org_unit = factory.SubFactory(OrgUnitFactory)
    employment_type = EmploymentType.FULL_TIME
    academic_title = factory.LazyFunction(lambda: {"en": "Professor", "ko": "교수", "zh-hans": "教授"})
    hire_date = factory.Faker("date_between", start_date="-20y", end_date="-1y")


class AdvisorAssignmentFactory(factory.django.DjangoModelFactory):
    class Meta:
        model = AdvisorAssignment

    student_record = factory.SubFactory(StudentRecordFactory)
    instructor = factory.SubFactory(InstructorFactory)
    role = AdvisorRole.PRIMARY
    start_date = factory.LazyFunction(lambda: timezone.localdate() - timedelta(days=365))


class StudentStatusChangeTypeFactory(factory.django.DjangoModelFactory):
    class Meta:
        model = StudentStatusChangeType

    code = factory.Sequence(lambda n: f"change_type_{n}")
    name = factory.LazyFunction(lambda: {"en": "Leave"})
    to_status = StudentStatus.ON_LEAVE
    from_statuses = factory.LazyFunction(lambda: [StudentStatus.ENROLLED.value])
    can_student_request = True


class StudentStatusChangeFactory(factory.django.DjangoModelFactory):
    class Meta:
        model = StudentStatusChange

    student_record = factory.SubFactory(StudentRecordFactory)
    type = factory.SubFactory(StudentStatusChangeTypeFactory)
    from_status = StudentStatus.ENROLLED
    to_status = StudentStatus.ON_LEAVE
    effective_date = factory.LazyFunction(lambda: timezone.localdate() + timedelta(days=7))
    reason = "Health"
    status = StatusChangeStatus.REQUESTED
    requested_at = factory.LazyFunction(lambda: timezone.now().replace(microsecond=0))
