def raw_payload(record: PiiTestRecord) -> str:
    return str(scalar("SELECT national_id_encrypted FROM pii_test_records WHERE id = %s", [record.pk]))


def test_stores_personal_data_encrypted_with_the_pii_key_not_in_plain_text(settings: Any) -> None:
    record = PiiTestRecord.objects.create(national_id_encrypted="900101-1234567")

    raw = raw_payload(record)
    assert "1234567" not in raw
    assert PiiTestRecord.objects.get(pk=record.pk).national_id_encrypted == "900101-1234567"
    # Not readable with another key (the original checked APP_KEY's decrypt()).
    other = PiiCipher("base64:" + base64.b64encode(os.urandom(32)).decode())
    with pytest.raises(DecryptError):
        other.decrypt(raw)


def test_reads_the_original_ciphertext_format() -> None:
    assert cipher().decrypt(LARAVEL_PAYLOAD) == "900101-1234567"
    assert cipher().is_encrypted_with_current_key(LARAVEL_PAYLOAD)
    payload = cipher().encrypt("x")
    decoded = base64.b64decode(payload).decode()
    assert decoded.startswith('{"iv":"') and '"mac":"","tag":"' in decoded


def test_computes_the_original_search_hash() -> None:
    assert pii_hash("900101-1234567", PiiType.NATIONAL_ID) == LARAVEL_HASH


def test_finds_records_by_exact_value_through_the_search_hash() -> None:
    record = PiiTestRecord.objects.create(national_id_encrypted="900101-1234567")
    PiiTestRecord.objects.create(national_id_encrypted="850505-2345678")

    assert PiiTestRecord.objects.where_pii("national_id", "9001011234567").get().pk == record.pk
    assert record.national_id_hash == LARAVEL_HASH


def test_keeps_the_hash_in_sync_and_the_ciphertext_when_the_value_is_unchanged() -> None:
    record = PiiTestRecord.objects.create(national_id_encrypted="900101-1234567")
    stored = raw_payload(record)

    loaded = PiiTestRecord.objects.get(pk=record.pk)
    loaded.note = "changed"
    loaded.save()
    assert raw_payload(record) == stored  # no re-encryption, so no spurious change

    loaded.national_id_encrypted = "850505-2345678"
    loaded.save()
    assert raw_payload(record) != stored
    assert PiiTestRecord.objects.where_pii("national_id", "850505-2345678").get().pk == record.pk

    loaded.national_id_encrypted = None
    loaded.save()
    assert PiiTestRecord.objects.filter(
        pk=record.pk, national_id_encrypted__isnull=True, national_id_hash__isnull=True
    ).exists()


def test_masks_values_for_display() -> None:
    record = PiiTestRecord.objects.create(national_id_encrypted="900101-1234567")

    assert record.masked_pii("national_id") == "**********4567"
    assert PiiType.EMAIL.mask("kim@example.com") == "k**@example.com"
    assert PiiType.PASSPORT_NUMBER.mask("M123") == "****"
    assert PiiTestRecord.encrypted_pii_attributes() == {"national_id": PiiType.NATIONAL_ID}


def test_normalizes_values_before_hashing() -> None:
    assert PiiType.NATIONAL_ID.normalize(" 900101-1234567 ") == "9001011234567"
    assert PiiType.PASSPORT_NUMBER.normalize("m 12-34") == "M1234"
    assert PiiType.EMAIL.normalize("  Kim@Example.COM ") == "kim@example.com"
    assert PiiType.GENERIC.normalize("  a b ") == "a b"


def test_never_exposes_the_plaintext_in_repr_or_serialization() -> None:
    from django.core import serializers

    record = PiiTestRecord.objects.create(national_id_encrypted="900101-1234567")

    assert "1234567" not in repr(record)
    assert "1234567" not in serializers.serialize("json", [record])


def test_reveals_a_value_only_with_the_view_sensitive_permission_and_records_it(grant: Any) -> None:
    record = PiiTestRecord.objects.create(national_id_encrypted="900101-1234567")
    officer = grant(make_user("officer@example.test"), "pii_test_records.view_sensitive")

    value = RevealSensitiveValue()(
        officer, record, "national_id", "pii_test_records.view_sensitive", "Certificate check"
    )

    event = SecurityEvent.objects.filter(type=SecurityEventType.SENSITIVE_DATA_REVEALED).get()
    assert value == "900101-1234567"
    assert event.user_id == officer.pk
    assert event.properties == {"attribute": "national_id", "reason": "Certificate check"}
    assert (event.subject_type, event.subject_id) == ("pii.piitestrecord", record.pk)

    with pytest.raises(PermissionDenied):
        RevealSensitiveValue()(make_user(), record, "national_id", "pii_test_records.view_sensitive")
    with pytest.raises(PermissionDenied):
        RevealSensitiveValue()(officer, record, "national_id", "pii_test_records.view")


def test_reencrypts_data_with_a_new_key_after_rotation(settings: Any) -> None:
    record = PiiTestRecord.objects.create(national_id_encrypted="900101-1234567")
    PiiTestRecord.objects.create()
    old_key = settings.PII_ENCRYPTION_KEY

    settings.PII_ENCRYPTION_KEY = "base64:" + base64.b64encode(os.urandom(32)).decode()
    settings.PII_PREVIOUS_KEYS = [old_key]

    before = raw_payload(record)
    assert not cipher().is_encrypted_with_current_key(before)

    out = StringIO()
    assert call_command("pii_reencrypt", "pii.PiiTestRecord", dry_run=True, stdout=out) == 0
    assert "Dry run: 1 record(s) still use a previous key." in out.getvalue()

    assert call_command("pii_reencrypt", "pii.PiiTestRecord", force=True, chunk=1, stdout=StringIO()) == 0

    after = raw_payload(record)
    assert cipher().is_encrypted_with_current_key(after)
    assert PiiTestRecord.objects.get(pk=record.pk).national_id_encrypted == "900101-1234567"
    assert PiiTestRecord.objects.where_pii("national_id", "9001011234567").exists()

    runs = ActivityLog.objects.filter(event="command.executed", properties__command="pii_reencrypt").order_by("id")
    assert [run.properties["result"].get("outdated_records") for run in runs] == [1, None]
    assert runs.last().properties["result"]["jobs"] == 2


