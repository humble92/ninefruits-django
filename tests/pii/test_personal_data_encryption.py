def test_generates_new_keys() -> None:
    out, err = StringIO(), StringIO()
    assert call_command("pii_generate_key", stdout=out, stderr=err) == 0

    lines = dict(line.split("=", 1) for line in out.getvalue().splitlines() if "=" in line)
    for name in ("PII_ENCRYPTION_KEY", "PII_HASH_KEY"):
        assert lines[name].startswith("base64:")
        assert len(base64.b64decode(lines[name][7:])) == 32
    assert "PII_PREVIOUS_KEYS" in err.getvalue()
    assert not ActivityLog.objects.filter(event="command.executed").exists()
