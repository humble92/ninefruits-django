-- RLS benchmark data (50,000 student records, 500,000 enrollments). Run as app_migrator on a
-- development database, then run rls_poc_queries.sql as app_runtime:
--   psql -U app_migrator -d laravel -f database/sql/benchmarks/rls_poc_setup.sql
--
-- Policy pattern: wrap function calls in scalar subqueries, e.g. (SELECT util.current_user_id()),
-- so they run once per query (InitPlan) instead of once per row. Results are in
-- porting/decisions/0003-row-level-security.md.
DROP TABLE IF EXISTS rls_bench_enrollments, rls_bench_student_records;

CREATE TABLE rls_bench_student_records (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    student_number text NOT NULL
);
CREATE TABLE rls_bench_enrollments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_record_id bigint NOT NULL REFERENCES rls_bench_student_records (id),
    grade text
);

INSERT INTO rls_bench_student_records (user_id, student_number)
SELECT g, 'S' || g FROM generate_series(1000000, 1049999) AS g;
INSERT INTO rls_bench_enrollments (student_record_id, grade)
SELECT sr.id, (ARRAY['A', 'B', 'C'])[1 + (n % 3)] FROM rls_bench_student_records AS sr, generate_series(1, 10) AS n;

CREATE INDEX ON rls_bench_student_records (user_id);
CREATE INDEX ON rls_bench_enrollments (student_record_id);

ALTER TABLE rls_bench_student_records ENABLE ROW LEVEL SECURITY;
ALTER TABLE rls_bench_enrollments ENABLE ROW LEVEL SECURITY;

CREATE POLICY rls_bench_student_records_owner_select ON rls_bench_student_records
    FOR SELECT USING (user_id = (SELECT util.current_user_id()));
CREATE POLICY rls_bench_student_records_staff_all ON rls_bench_student_records
    FOR ALL USING ((SELECT util.has_permission('users.view')));
CREATE POLICY rls_bench_enrollments_owner_select ON rls_bench_enrollments
    FOR SELECT USING (student_record_id IN (
                SELECT sr.id FROM rls_bench_student_records AS sr WHERE sr.user_id = (SELECT util.current_user_id())
            ));
CREATE POLICY rls_bench_enrollments_staff_all ON rls_bench_enrollments
    FOR ALL USING ((SELECT util.has_permission('users.view')));

ANALYZE rls_bench_student_records;
ANALYZE rls_bench_enrollments;

